import { mkdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.dirname(fileURLToPath(import.meta.url));

/** Small programs copied into the web bundle and seeded into OPFS. */
export const SEED_FILES = [
  "common/drill_7_20.h",
  "pellet/motor_mount_plate/11_holes.h",
  "print-head/v5/toolboss/pre-all.h",
  "lydia-v4/m8_tap.h",
  "moulds/christine/v2-bottom/socket-contour.h",
];

export function writeWebSeeds() {
  const sampleDir = path.resolve(root, "../samples");
  const files = {};
  for (const rel of SEED_FILES) {
    const abs = path.join(sampleDir, rel);
    try {
      files[rel] = readFileSync(abs, "utf8");
    } catch {
      throw new Error(`Web seed missing: ${rel}`);
    }
  }
  const outDir = path.resolve(root, "src/generated");
  mkdirSync(outDir, { recursive: true });
  const body = `/* Generated by write-web-seeds.mjs. Do not edit. */\nexport const SEEDS: Record<string, string> = ${JSON.stringify(files)};\n`;
  writeFileSync(path.join(outDir, "web-seeds.ts"), body);
  return files;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeWebSeeds();
}
